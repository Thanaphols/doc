def mark_thai(run, font_size=16, bold=False, italic=False):
    run.bold = bold
    run.italic = italic
    rPr = run._r.get_or_add_rPr()
    for tag in ("w:rFonts", "w:cs", "w:sz", "w:szCs", "w:lang"):
        for old in rPr.findall(qn(tag)):
            rPr.remove(old)
    fonts = OxmlElement("w:rFonts")
    for a in ("w:ascii", "w:hAnsi", "w:cs"):
        fonts.set(qn(a), "TH SarabunPSK")
    fonts.set(qn("w:hint"), "cs")
    lang = OxmlElement("w:lang")
    lang.set(qn("w:val"), "en-US")
    lang.set(qn("w:eastAsia"), "en-US")
    lang.set(qn("w:bidi"), "th-TH")

    sz = OxmlElement("w:sz")
    sz.set(qn("w:val"), str(int(font_size * 2)))
    szCs = OxmlElement("w:szCs")
    szCs.set(qn("w:val"), str(int(font_size * 2)))

    rPr.insert(0, fonts)
    rPr.append(sz)
    rPr.append(szCs)
    rPr.append(OxmlElement("w:cs"))
    rPr.append(lang)


def create_base_doc():
    doc = docx.Document(TEMPLATE)
    for el in list(doc.element.body):
        if el.tag != qn("w:sectPr"):
            doc.element.body.remove(el)
    s = doc.sections[0]
    s.different_first_page_header_footer = True
    s.top_margin = Cm(5.08)  # first page of appendix = 2 inches
    s.bottom_margin = Cm(2.54)
    s.left_margin = Cm(3.81)
    s.right_margin = Cm(2.54)
    return doc


def add_p(doc, text="", align=WD_ALIGN_PARAGRAPH.THAI_JUSTIFY, bold=False, italic=False,
          size=16, space_b=0, space_a=6, first_indent_cm=1.8, left_indent_cm=0):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    pf.space_before = Pt(space_b)
    pf.space_after = Pt(space_a)
    pf.first_line_indent = Cm(first_indent_cm)
    pf.left_indent = Cm(left_indent_cm)
    pf.line_spacing = 1.0
    if text:
        r = p.add_run(text)
        mark_thai(r, font_size=size, bold=bold, italic=italic)
    return p


def add_heading_l2(doc, text):
    """Level 2 heading (e.g. ก.1, ก.2): bold, flush left 0 cm, 16pt"""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    pf = p.paragraph_format
    pf.first_line_indent = Cm(0)
    pf.left_indent = Cm(0)
    pf.space_before = Pt(14)
    pf.space_after = Pt(6)
    pf.keep_with_next = True
    r = p.add_run(text)
    mark_thai(r, font_size=16, bold=True)
    return p


def add_heading_l3(doc, text):
    """Level 3 heading (e.g. ก.5.1): normal weight, indent 1.8 cm, wrap to 0 cm, 16pt"""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    pf = p.paragraph_format
    pf.first_line_indent = Cm(1.8)
    pf.left_indent = Cm(0)
    pf.space_before = Pt(8)
    pf.space_after = Pt(4)
    pf.keep_with_next = True
    r = p.add_run(text)
    mark_thai(r, font_size=16, bold=False)
    return p


def add_figure_box(doc, fig_num_str, title):
    """Adds a centered 1x1 table placeholder box (width 5.5 cm, height 9.5 cm)
    with a caption below: รูปที่ ก.N  <ชื่อ> (centered, 16pt, 2 spaces)."""
    tbl = doc.add_table(rows=1, cols=1)
    tblPr = tbl._tbl.tblPr
    jc = OxmlElement("w:jc")
    jc.set(qn("w:val"), "center")
    tblPr.append(jc)

    tblBorders = OxmlElement("w:tblBorders")
    for b in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{b}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:space"), "0")
        el.set(qn("w:color"), "auto")
        tblBorders.append(el)
    for b in ("insideH", "insideV"):
        el = OxmlElement(f"w:{b}")
        el.set(qn("w:val"), "none")
        tblBorders.append(el)
    tblPr.append(tblBorders)

    row = tbl.rows[0]
    trPr = row._tr.get_or_add_trPr()
    trHeight = OxmlElement("w:trHeight")
    trHeight.set(qn("w:val"), "5386")  # ~9.5 cm
    trHeight.set(qn("w:hRule"), "atLeast")
    trPr.append(trHeight)
    trPr.append(OxmlElement("w:cantSplit"))

    cell = row.cells[0]
    cell.width = Cm(5.5)
    p_inside = cell.paragraphs[0]
    p_inside.paragraph_format.space_before = Pt(0)
    p_inside.paragraph_format.space_after = Pt(0)

    # Caption below box
    p_cap = doc.add_paragraph()
    p_cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pf_cap = p_cap.paragraph_format
    pf_cap.space_before = Pt(6)
    pf_cap.space_after = Pt(12)
    pf_cap.first_line_indent = Cm(0)
    pf_cap.left_indent = Cm(0)
    pf_cap.keep_with_next = False
    r_cap = p_cap.add_run(f"รูปที่ {fig_num_str}  {title}")
    mark_thai(r_cap, font_size=16, bold=False)
    return tbl, p_cap


