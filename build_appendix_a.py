def export_pdf(docx_path, pdf_path):
    word = win32com.client.DispatchEx("Word.Application")
    word.Visible = False
    word.DisplayAlerts = 0
    try:
        d = word.Documents.Open(os.path.abspath(docx_path))
        d.Repaginate()
        d.ExportAsFixedFormat(os.path.abspath(pdf_path), 17)
        d.Close(False)
    finally:
        word.Quit()


